    private static bool Consentita(Guida g, Func<string, bool> haPermesso) => g.Permesso.Split('|').Any(haPermesso);

    public static IEnumerable<Guida> Visibili(Func<string, bool> haPermesso) => Elenco.Where(g => Consentita(g, haPermesso));

    public static Guida? PerCodice(string codice, Func<string, bool> haPermesso) =>
        Elenco.FirstOrDefault(g => string.Equals(g.Codice, codice, StringComparison.OrdinalIgnoreCase) && Consentita(g, haPermesso));

    /// <summary>Guida della pagina aperta (confronto sull'inizio del percorso), se l'utente può vederla.</summary>
    public static Guida? PerPercorso(string? percorso, Func<string, bool> haPermesso) =>
        string.IsNullOrEmpty(percorso) ? null : Visibili(haPermesso).FirstOrDefault(g => g.Percorsi.Any(p =>
            percorso.Equals(p, StringComparison.OrdinalIgnoreCase) || percorso.StartsWith(p + "/", StringComparison.OrdinalIgnoreCase)));
